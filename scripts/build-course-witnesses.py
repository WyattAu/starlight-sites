#!/usr/bin/env python3
"""Extract formal-witness Lean blocks from course pages into lean/Witnesses.lean.

Scans the course's written stage pages for ```lean fences, concatenates
the blocks in page order, and writes lean/Witnesses.lean (generated; do
not edit by hand). The lean-proof CI job regenerates this file and then
compiles it, so a witness that stops compiling fails the build exactly as
a broken course map does.

Usage:
  python3 scripts/build-course-witnesses.py           # regenerate
  python3 scripts/build-course-witnesses.py --check   # exit 1 if stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "sites" / "mathematics" / "src" / "content" / "docs" / "17-core-course"
OUT = ROOT / "lean" / "Witnesses.lean"
PAGES = [
    "stage-b-counting.md",
]

HEADER = """/-!
# Formal witnesses of the Core Course

Generated by scripts/build-course-witnesses.py from the ```lean blocks in
the written stage pages. Every block is a compiling proof, core Lean only.
The prose proofs on the pages remain the proofs of record; these boxes are
machine-verified restatements. Regenerated on every push; a witness that
stops compiling fails the build.
-/"""


def main():
    blocks = []
    for name in PAGES:
        path = DOCS / name
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        for m in re.finditer(r"^```lean\n(.*?)^```", text, re.M | re.S):
            body = m.group(1).rstrip() + "\n"
            blocks.append((name, body))

    content = HEADER + "\n\n" + "\n".join(
        f"/-! From `{name}` -/\n\n{body}" for name, body in blocks
    )
    content = content.rstrip() + "\n"

    if "--check" in sys.argv:
        if OUT.exists() and OUT.read_text(encoding="utf-8") == content:
            print(f"witnesses up to date: {len(blocks)} blocks")
            return
        print("witnesses STALE: run python3 scripts/build-course-witnesses.py")
        sys.exit(1)

    OUT.write_text(content, encoding="utf-8")
    print(f"witnesses written: {len(blocks)} blocks from {len(PAGES)} pages")


if __name__ == "__main__":
    main()
