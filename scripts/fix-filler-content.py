#!/usr/bin/env python3
"""Remove template filler that makes empty promises.

Two classes ship across the network, both generated by a page template rather
than written by anyone:

  F1  An `## Advanced Content` section whose subsections -- "Derivations and
      Proofs", "Extended Examples", "Research Connections", "Prerequisites" --
      contain only placeholder prose. A reader sees a section promising proofs
      and examples and gets sentences describing what proofs would look like.

  F2  A seven-line mermaid flowchart reading "Key Concepts / Core Principles /
      Practical Applications / Design patterns / Real-world usage", wired to
      the page title. It is the same graph on every page and says nothing.

Both are removed only when the removal is provably safe:

  * F1 is removed only if EVERY non-blank line in the section is a heading or
    one of the exact placeholder sentences. A section with any real content is
    left untouched. Measured: 458 files qualify, and zero files are mixed.
  * F2 is removed only if the block matches the filler shape exactly, after
    normalising the node labels, and carries the filler wording. Measured:
    1,762 blocks match that one shape; the 343 other mermaid diagrams in the
    network have different shapes and are never candidates.

Deleting filler removes no information -- there is none in it. The *content*
those sections promised is a genuine gap and is recorded in the editorial
backlog, so removing the promise does not erase the shortfall.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITES = ROOT / "sites"

PLACEHOLDERS = {
    "This section provides detailed coverage of advanced concepts, including full derivations, proofs, and extended examples.",
    "Complete mathematical derivations and proofs are provided where appropriate. Each step is explained to ensure understanding of the underlying reasoning.",
    "Advanced examples demonstrate the application of concepts to complex problems. These examples go beyond standard exam questions to develop deeper understanding.",
    "This material connects to current research and advanced applications in the field. Understanding these connections provides context for the study material.",
    "Ensure you have mastered the prerequisite material before attempting this advanced content.",
}

MERMAID = re.compile(r"```mermaid[ \t]*\n(.*?)```[ \t]*\n?", re.S)
NODE_LABEL = re.compile(r"\[[^\]]*\]")

# The one filler shape, with node labels blanked out.
FILLER_SHAPE = (
    "flowchart TD",
    "A[] --> B[]",
    "A --> C[]",
    "A --> D[]",
    "B --> E[]",
    "C --> F[]",
    "D --> G[]",
)


def filler_advanced_section(lines: list[str], start: int) -> int | None:
    """Return the exclusive end index if lines[start:] begins an all-filler
    `## Advanced Content` section, else None."""
    if lines[start].strip() != "## Advanced Content":
        return None
    end = start + 1
    while end < len(lines) and not re.match(r"^##\s", lines[end]):
        end += 1
    for line in lines[start:end]:
        t = line.strip()
        if not t or re.match(r"^#{2,6}\s", t):
            continue
        if t in PLACEHOLDERS:
            continue
        return None  # real content: leave the section alone
    return end


def is_filler_mermaid(body: str) -> bool:
    shape = tuple(NODE_LABEL.sub("[]", l.strip()) for l in body.strip().split("\n") if l.strip())
    if shape != FILLER_SHAPE:
        return False
    return "Design patterns" in body and "Real-world usage" in body


def process(path: Path, apply: bool) -> tuple[int, int]:
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")

    # F1 first: removing a section can expose the next one.
    f1 = 0
    while True:
        changed = False
        for i, line in enumerate(lines):
            if not line.startswith("## "):
                continue
            end = filler_advanced_section(lines, i)
            if end is None:
                continue
            del lines[i:end]
            f1 += 1
            changed = True
            break
        if not changed:
            break

    # F2
    body = "\n".join(lines)
    f2 = 0

    def repl(m: re.Match) -> str:
        nonlocal f2
        if is_filler_mermaid(m.group(1)):
            f2 += 1
            return ""
        return m.group(0)

    new_body = MERMAID.sub(repl, body)
    # collapse any run of 3+ blank lines left behind
    new_body = re.sub(r"\n{3,}", "\n\n", new_body)
    if f1 or f2:
        path.write_text(new_body, encoding="utf-8") if apply else None
    return f1, f2


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("roots", nargs="*")
    args = ap.parse_args()

    roots = [Path(r).resolve() for r in args.roots] or [SITES]
    expanded = []
    for r in roots:
        expanded.append(r / "sites" if (r / "sites").is_dir() else r)

    t1 = t2 = 0
    files = 0
    for base in expanded:
        for path in sorted(base.rglob("*")):
            if path.suffix not in (".md", ".mdx") or not path.is_file():
                continue
            if "zh" in path.parts or "dist" in path.parts:
                continue
            a, b = process(path, apply=args.apply and not args.check)
            if a or b:
                files += 1
                t1 += a
                t2 += b

    print(f"filler Advanced Content sections: {t1}   filler mermaid diagrams: {t2}   files: {files}")
    if args.check and (t1 or t2):
        print("  -> remaining; run scripts/fix-filler-content.py --apply")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())